package io.github.aqsama.fandroidterminal.terminal

/**
 * A terminal color scheme: default foreground/background, cursor/selection and the 16 ANSI colors.
 * Values are the publicly documented palettes of each named scheme (color values only, no code);
 * "Graphite" and "Paper" keep the Terax-derived ANSI data listed in THIRD_PARTY_NOTICES.md.
 */
data class TerminalScheme(
    val id: String,
    val name: String,
    val dark: Boolean,
    val foreground: Int,
    val background: Int,
    val selection: Int,
    val ansi: IntArray,
) {
    init { require(ansi.size == 16) }
    override fun equals(other: Any?) = other is TerminalScheme && other.id == id
    override fun hashCode() = id.hashCode()
}

private fun scheme(id: String, name: String, dark: Boolean, fg: Int, bg: Int, sel: Int, vararg ansi: Int) =
    TerminalScheme(id, name, dark, fg or OPAQUE, bg or OPAQUE, sel or OPAQUE, ansi.map { it or OPAQUE }.toIntArray())

